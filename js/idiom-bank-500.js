  // 4. 高年級：隨機新聞抓漏王題目（從 100+ 易錯成語中隨機生成新聞標題！）
  function generateNewsBugs(baseBugs, extraCount = 20) {
    const bugPool = ALL_IDIOMS.filter((x) => x.cat === "bug" && x.wrongSeg && x.wrongSeg !== x.idiom);
    const categories = ["校園特派快報", "語文糾察隊", "上林小小記者", "藝文速報", "科學特派"];
    const headlineTemplates = [
      (w) => `上林國小校慶活動熱鬧展開，全校師生表現令人讚賞，報導中卻誤寫成「${w}」！`,
      (w) => `本週校園週報頭條提醒同學們閱讀時要細心，文中這句「${w}」其實藏著一個錯別字！`,
      (w) => `小小記者採訪班級閱讀競賽，稿件裡寫到「大家都是${w}的好榜樣」，請幫他捉蟲修正！`,
      (w) => `語文小報快訊：編輯在趕稿時不小心把成語打成「${w}」，快用放大鏡找出錯字吧！`
    ];

    const extras = shuffle(bugPool)
      .slice(0, extraCount)
      .map((item, idx) => {
        const headline = headlineTemplates[idx % headlineTemplates.length](item.wrongSeg);
        const wrongIdx = headline.indexOf(item.wrongSeg);
        let wrongChar = item.wrongSeg[0];
        let correctChar = item.idiom[0];
        let wrongCharIndex = wrongIdx;
        for (let k = 0; k < 4; k++) {
          if (item.wrongSeg[k] !== item.idiom[k]) {
            wrongChar = item.wrongSeg[k];
            correctChar = item.idiom[k];
            wrongCharIndex = wrongIdx + k;
            break;
          }
        }
        const distractorSet = new Set([item.idiom, item.wrongSeg]);
        pickDistractors(item.idiom, bugPool, 2).forEach((d) => distractorSet.add(d));
        return {
          id: "rnd-news-" + item.idiom,
          category: categories[idx % categories.length],
          headline,
          wrongSegment: item.wrongSeg,
          wrongCharIndex,
          wrongChar,
          correctSegment: item.idiom,
          correctChar,
          options: shuffle(Array.from(distractorSet)),
          explanation: `「${item.idiom}」：${item.meaning} ${item.wrongExplain}`
        };
      });

    return shuffle(baseBugs || []).concat(extras);
  }

  // 5. 全站 500+ 成語隨機自由刷題器（支援依分類篩選）
  function drawRandomQuiz(category = "all", excludeIds = []) {
    const ex = new Set(excludeIds || []);
    let pool = category === "all" ? ALL_IDIOMS : ALL_IDIOMS.filter((x) => x.cat === category);
    if (!pool.length) pool = ALL_IDIOMS;
    let fresh = pool.filter((x) => !ex.has(x.id));
    if (!fresh.length) fresh = pool;
    const target = fresh[Math.floor(Math.random() * fresh.length)];
    const distractors = pickDistractors(target.idiom, pool.length >= 4 ? pool : ALL_IDIOMS, 3);
    const catLabelMap = {
      num: "🔢 數字成語",
      nature: "🦊 動植物與自然",
      bug: "🗞️ 易錯字必考",
      life: "💬 生活常用",
      study: "📚 學習勵志",
      story: "📖 歷史典故"
    };
    return {
      id: target.id,
      idiom: target.idiom,
      meaning: target.meaning,
      cat: target.cat,
      catLabel: catLabelMap[target.cat] || "🌟 精選成語",
      extra: target.extra,
      wrongSeg: target.wrongSeg,
      wrongExplain: target.wrongExplain,
      options: shuffle([target.idiom].concat(distractors))
    };
  }

  function pickRandomIdioms(count = 4) {
    return shuffle(ALL_IDIOMS).slice(0, count).map((x) => x.idiom);
  }

  function getStats() {
    const counts = { total: ALL_IDIOMS.length, num: 0, nature: 0, bug: 0, life: 0, study: 0, story: 0 };
    ALL_IDIOMS.forEach((x) => {
      if (counts[x.cat] !== undefined) counts[x.cat] += 1;
    });
    return counts;
  }

